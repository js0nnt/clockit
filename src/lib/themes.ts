const solid = (a: string): ColorSpec => ({ a, b: a, kind: 'solid', rotation: 0, x: 50, y: 50 })
const linear = (a: string, b: string, rotation = 160): ColorSpec => ({
  a,
  b,
  kind: 'linear',
  rotation,
  x: 50,
  y: 50,
})
const radial = (a: string, b: string, x = 50, y = 30): ColorSpec => ({
  a,
  b,
  kind: 'radial',
  rotation: 0,
  x,
  y,
})

